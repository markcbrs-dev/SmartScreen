    def extract_industries(self, text: str) -> List[str]:
        """Extract industry information"""
        industries_found = []
        text_lower = text.lower()

        for industry in self.industries:
            pattern = r'\b' + re.escape(industry) + r'\b'
            if re.search(pattern, text_lower):
                industries_found.append(industry.title())

        return industries_found

    def extract_sections_by_keywords(self, text: str, keywords: List[str]) -> Dict[str, str]:
        """Extract text sections based on keywords"""
        sections = {}
        lines = text.split('\n')

        for i, line in enumerate(lines):
            line_lower = line.lower().strip()
            for keyword in keywords:
                if keyword in line_lower:
                    # Found a section header
                    section_content = []
                    # Collect subsequent lines until next header or empty
                    for j in range(i + 1, len(lines)):
                        next_line = lines[j].strip()
                        if not next_line or any(kw in next_line.lower() for kw in keywords):
                            break
                        if next_line:
                            section_content.append(next_line)

                    if section_content:
                        sections[line.strip()] = '\n'.join(section_content)
                    break

        return sections

    def parse_job_description(self, file_path: str) -> JobEntity:
        """
        Parse job description file and extract all entities

        Args:
            file_path: Path to job description file (DOCX or TXT)

        Returns:
            JobEntity object with extracted information
        """
        print(f"Parsing job description: {file_path}")

        # Extract text
        raw_text = self.extract_text(file_path)

        if not raw_text:
            print(f"Warning: No text extracted from {file_path}")
            return JobEntity(raw_text="")

        # Create JobEntity
        job_data = JobEntity(raw_text=raw_text)

        # Extract basic information
        job_data.job_title = self.extract_job_title(raw_text)
        job_data.company = self.extract_company(raw_text)
        job_data.location = self.extract_location(raw_text)
        job_data.employment_type = self.extract_employment_type(raw_text)
        job_data.experience_level = self.extract_experience_level(raw_text)
        job_data.salary_range = self.extract_salary_range(raw_text)
        job_data.remote_option = self.extract_remote_option(raw_text)

        # Extract skills with section-based extraction
        skill_sections = ['skills', 'technical skills', 'requirements', 'qualifications']
        required_skills, preferred_skills = self.extract_skills(raw_text, skill_sections)
        job_data.required_skills = required_skills
        job_data.preferred_skills = preferred_skills

        # Extract other sections
        job_data.responsibilities = self.extract_responsibilities(raw_text)
        job_data.qualifications = self.extract_qualifications(raw_text)
        job_data.education_requirements = self.extract_education_requirements(raw_text)
        job_data.certifications = self.extract_certifications(raw_text)
        job_data.benefits = self.extract_benefits(raw_text)
        job_data.industries = self.extract_industries(raw_text)

        return job_data

    def parse_multiple_jobs(self, folder_path: str) -> List[JobEntity]:
        """
        Parse all job descriptions in a folder

        Args:
            folder_path: Path to folder containing job descriptions

        Returns:
            List of JobEntity objects
        """
        jobs = []

        if not os.path.exists(folder_path):
            print(f"Error: Folder not found: {folder_path}")
            return jobs

        for filename in os.listdir(folder_path):
            file_path = os.path.join(folder_path, filename)

            if os.path.isfile(file_path):
                ext = os.path.splitext(filename)[1].lower()

                if ext in ['.docx', '.doc', '.txt']:
                    try:
                        job = self.parse_job_description(file_path)
                        jobs.append(job)
                        print(f"Successfully parsed: {filename}")
                    except Exception as e:
                        print(f"Failed to parse {filename}: {str(e)}")

        return jobs

