def main():
    """Main function for command-line usage"""
    # Check if we're in Colab or similar environment
    is_colab = 'google.colab' in sys.modules or 'IPython' in str(type(sys.stdout))

    if is_colab or len(sys.argv) == 1:
        # Run example usage in Colab or when no arguments provided
        example_usage()
    else:
        # Parse command line arguments
        import argparse

        parser = argparse.ArgumentParser(description='Resume Parser with NER')
        parser.add_argument('input', help='Path to resume file or folder')
        parser.add_argument('--output', '-o', default='resumes_analysis.csv',
                          help='Output CSV file path')
        parser.add_argument('--model', '-m', default='en_core_web_sm',
                          help='SpaCy model to use')

        # Parse known arguments only (handles Colab's -f argument)
        args, _ = parser.parse_known_args()

        # Initialize parser
        parser_obj = ResumeParser(nlp_model=args.model)

        if os.path.isfile(args.input):
            # Parse single file
            resume = parser_obj.parse_resume(args.input)
            display_results(resume)

            # Save to CSV
            save_to_csv([resume], args.output)

        elif os.path.isdir(args.input):
            # Parse all resumes in folder
            resumes = parser_obj.parse_multiple_resumes(args.input)

            print(f"\n✅ Parsed {len(resumes)} resume(s)")

            if resumes:
                # Display first resume as example
                display_results(resumes[0])

                # Save all to CSV
                df = save_to_csv(resumes, args.output)

                # Print summary
                print(f"\n📊 SUMMARY STATISTICS:")
                print(f"   Average skills per resume: {df['Skills'].str.count(',').mean() + 1:.1f}")
                print(f"   Resumes with email: {(df['Email'] != 'Not Found').sum()}/{len(df)}")
                print(f"   Resumes with phone: {(df['Phone'] != 'Not Found').sum()}/{len(df)}")

        else:
            print(f"Error: {args.input} is not a valid file or directory")

if __name__ == "__main__":
    main()

