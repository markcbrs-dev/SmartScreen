class ResumeParser:
    """Main class for parsing resumes from PDF and DOCX files"""

    def __init__(self, nlp_model: str = "en_core_web_sm"):
        """
        Initialize the Resume Parser

        Args:
            nlp_model: SpaCy model to use for NER
        """
        self.nlp = None
        self.common_skills = self._load_common_skills()

        if NLP_AVAILABLE:
            try:
                self.nlp = spacy.load(nlp_model)
            except OSError:
                print(f"Model {nlp_model} not found. Please download it using:")
                print(f"python -m spacy download {nlp_model}")
                print("Or install with: spacy.cli.download('{nlp_model}')")

    def _load_common_skills(self) -> List[str]:
        """Load common technical skills for enhanced extraction"""
        return [
            'python', 'java', 'javascript', 'c++', 'c#', 'ruby', 'go', 'rust',
            'html', 'css', 'react', 'angular', 'vue', 'node.js', 'django', 'flask',
            'sql', 'mongodb', 'postgresql', 'mysql', 'aws', 'azure', 'gcp',
            'docker', 'kubernetes', 'jenkins', 'git', 'linux', 'unix',
            'machine learning', 'deep learning', 'ai', 'data analysis',
            'tableau', 'power bi', 'excel', 'agile', 'scrum', 'devops'
        ]

    def extract_text_from_pdf(self, file_path: str) -> str:
        """Extract text from PDF file using multiple methods for better accuracy"""
        text = ""

        # Method 1: Use pdfplumber (better for complex layouts)
        try:
            with pdfplumber.open(file_path) as pdf:
                for page in pdf.pages:
                    page_text = page.extract_text()
                    if page_text:
                        text += page_text + "\n"
        except Exception as e:
            print(f"pdfplumber failed: {e}")
            text = ""

        # If pdfplumber didn't extract much, try PyPDF2
        if len(text.strip()) < 100:
            try:
                with open(file_path, 'rb') as file:
                    pdf_reader = PyPDF2.PdfReader(file)
                    for page in pdf_reader.pages:
                        page_text = page.extract_text()
                        if page_text:
                            text += page_text + "\n"
            except Exception as e:
                print(f"PyPDF2 failed: {e}")

        return text.strip()

    def extract_text_from_docx(self, file_path: str) -> str:
        """Extract text from DOCX file"""
        if not DOCX_AVAILABLE:
            raise ImportError("python-docx not installed. Install with: pip install python-docx")

        try:
            doc = Document(file_path)
            full_text = []

            for paragraph in doc.paragraphs:
                if paragraph.text.strip():
                    full_text.append(paragraph.text)

            # Also extract text from tables
            for table in doc.tables:
                for row in table.rows:
                    for cell in row.cells:
                        if cell.text.strip():
                            full_text.append(cell.text)

            return "\n".join(full_text)
        except Exception as e:
            print(f"Error reading DOCX file: {e}")
            return ""

    def extract_text(self, file_path: str) -> str:
        """Extract text from file based on extension"""
        if not os.path.exists(file_path):
            raise FileNotFoundError(f"File not found: {file_path}")

        ext = os.path.splitext(file_path)[1].lower()

        if ext == '.pdf':
            if not PDF_AVAILABLE:
                raise ImportError("PDF libraries not installed. Install with: pip install PyPDF2 pdfplumber")
            return self.extract_text_from_pdf(file_path)
        elif ext in ['.docx', '.doc']:
            if not DOCX_AVAILABLE:
                raise ImportError("python-docx not installed. Install with: pip install python-docx")
            return self.extract_text_from_docx(file_path)
        else:
            raise ValueError(f"Unsupported file format: {ext}. Supported: .pdf, .docx")

    def extract_email(self, text: str) -> Optional[str]:
        """Extract email address from text"""
        email_pattern = r'\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Z|a-z]{2,}\b'
        emails = re.findall(email_pattern, text, re.IGNORECASE)
        return emails[0] if emails else None

    def extract_phone(self, text: str) -> Optional[str]:
        """Extract phone number from text"""
        # Multiple phone number patterns
        patterns = [
            r'\b\d{3}[-.]?\d{3}[-.]?\d{4}\b',  # 123-456-7890
            r'\b\(\d{3}\)\s*\d{3}[-.]?\d{4}\b',  # (123) 456-7890
            r'\b\d{10}\b',  # 1234567890
            r'\b\d{3}\s\d{3}\s\d{4}\b',  # 123 456 7890
            r'\+\d{1,3}\s?\d{3}[-.]?\d{3}[-.]?\d{4}\b',  # +1 123-456-7890
        ]

        for pattern in patterns:
            phones = re.findall(pattern, text)
            if phones:
                return phones[0]
        return None

    def extract_skills(self, text: str) -> List[str]:
        """Extract technical skills from text"""
        text_lower = text.lower()
        found_skills = []

        # Check for common skills
        for skill in self.common_skills:
            pattern = r'\b' + re.escape(skill) + r'\b'
            if re.search(pattern, text_lower):
                found_skills.append(skill.title())

        # Use NER for additional skill extraction
        if self.nlp:
            doc = self.nlp(text)
            for ent in doc.ents:
                if ent.label_ in ["ORG", "PRODUCT"]:
                    # Some organizations/products could be skills
                    ent_lower = ent.text.lower()
                    if any(tech in ent_lower for tech in ['aws', 'azure', 'react', 'angular', 'docker', 'kubernetes']):
                        if ent.text not in found_skills:
                            found_skills.append(ent.text)

        return list(set(found_skills))  # Remove duplicates

    def extract_education(self, text: str) -> List[str]:
        """Extract education information"""
        education_keywords = [
            'university', 'college', 'institute', 'school', 'academy',
            'bachelor', 'master', 'phd', 'mba', 'bsc', 'msc', 'ba', 'ma',
            'degree', 'diploma', 'certificate', 'coursework', 'graduated',
            'education', 'qualification', 'certification'
        ]

        # Split by newlines first, then by sentences
        lines = text.split('\n')
        education_info = []

        for line in lines:
            line_lower = line.lower()
            if any(keyword in line_lower for keyword in education_keywords):
                # Clean up the line
                clean_line = ' '.join(line.split())
                if 10 < len(clean_line) < 200:  # Avoid very short or long lines
                    education_info.append(clean_line)

        return education_info[:5]  # Return top 5 education entries

    def extract_experience(self, text: str) -> List[str]:
        """Extract experience information"""
        experience_keywords = [
            'experience', 'worked', 'employed', 'position', 'role',
            'job', 'responsibilities', 'duties', 'achievements',
            'years', 'months', 'currently', 'previous', 'former',
            'senior', 'junior', 'lead', 'manager', 'director',
            'developer', 'engineer', 'analyst', 'specialist'
        ]

        lines = text.split('\n')
        experience_info = []

        for line in lines:
            line_lower = line.lower()
            if any(keyword in line_lower for keyword in experience_keywords):
                clean_line = ' '.join(line.split())
                if 20 < len(clean_line) < 200:
                    experience_info.append(clean_line)

        return experience_info[:10]  # Return top 10 experience entries

    def extract_with_ner(self, text: str) -> Dict[str, List[str]]:
        """Extract entities using SpaCy NER"""
        if not self.nlp:
            return {}

        doc = self.nlp(text)
        entities = {
            'PERSON': [],
            'ORG': [],
            'GPE': [],  # Geographical Political Entities (locations)
            'DATE': [],
            'PRODUCT': [],
            'NORP': [],  # Nationalities or religious/political groups
        }

        for ent in doc.ents:
            if ent.label_ in entities:
                entities[ent.label_].append(ent.text)

        # Deduplicate
        for key in entities:
            entities[key] = list(set(entities[key]))

        return entities

    def parse_resume(self, file_path: str) -> ResumeEntity:
        """
        Parse resume file and extract all entities

        Args:
            file_path: Path to resume file (PDF or DOCX)

        Returns:
            ResumeEntity object with extracted information
        """
        print(f"Parsing resume: {file_path}")

        # Extract text
        raw_text = self.extract_text(file_path)

        if not raw_text:
            print(f"Warning: No text extracted from {file_path}")
            return ResumeEntity(raw_text="")

        # Create ResumeEntity
        resume_data = ResumeEntity(raw_text=raw_text)

        # Extract basic information
        resume_data.email = self.extract_email(raw_text)
        resume_data.phone = self.extract_phone(raw_text)
        resume_data.skills = self.extract_skills(raw_text)
        resume_data.education = self.extract_education(raw_text)
        resume_data.experience = self.extract_experience(raw_text)

        # Extract entities using NER
        if self.nlp:
            ner_entities = self.extract_with_ner(raw_text)
            resume_data.organizations = ner_entities.get('ORG', [])
            resume_data.locations = ner_entities.get('GPE', [])

            # Try to extract name from PERSON entities
            if ner_entities.get('PERSON'):
                # Filter out titles and use the first likely name
                for person in ner_entities['PERSON']:
                    if len(person.split()) >= 2 and len(person) < 50:
                        resume_data.name = person
                        break
                if not resume_data.name and ner_entities['PERSON']:
                    resume_data.name = ner_entities['PERSON'][0]

        return resume_data

    def parse_multiple_resumes(self, folder_path: str) -> List[ResumeEntity]:
        """
        Parse all resumes in a folder

        Args:
            folder_path: Path to folder containing resumes

        Returns:
            List of ResumeEntity objects
        """
        resumes = []

        if not os.path.exists(folder_path):
            print(f"Error: Folder not found: {folder_path}")
            return resumes

        for filename in os.listdir(folder_path):
            file_path = os.path.join(folder_path, filename)

            if os.path.isfile(file_path):
                ext = os.path.splitext(filename)[1].lower()

                if ext in ['.pdf', '.docx', '.doc']:
                    try:
                        resume = self.parse_resume(file_path)
                        resumes.append(resume)
                        print(f"Successfully parsed: {filename}")
                    except Exception as e:
                        print(f"Failed to parse {filename}: {str(e)}")

        return resumes

def save_to_csv(resumes: List[ResumeEntity], output_file: str = "resumes_analysis.csv"):
    """Save extracted resume data to CSV"""
    data = []

    for i, resume in enumerate(resumes):
        row = {
            'Resume_ID': i + 1,
            'Name': resume.name or 'Not Found',
            'Email': resume.email or 'Not Found',
            'Phone': resume.phone or 'Not Found',
            'Skills': ', '.join(resume.skills) if resume.skills else 'Not Found',
            'Education_Count': len(resume.education),
            'Experience_Count': len(resume.experience),
            'Organizations': ', '.join(resume.organizations[:5]) if resume.organizations else 'Not Found',
            'Locations': ', '.join(resume.locations[:3]) if resume.locations else 'Not Found',
        }
        data.append(row)

    df = pd.DataFrame(data)
    df.to_csv(output_file, index=False)
    print(f"Results saved to {output_file}")
    return df

