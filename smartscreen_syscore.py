class ResumeJobMatcher:
    """Main class for matching resumes with job descriptions"""

    def __init__(self, weights: Optional[MatchingWeights] = None, use_ml: bool = True):
        """
        Initialize the Resume-Job Matcher

        Args:
            weights: Custom weights for matching criteria
            use_ml: Whether to use ML-based matching (requires scikit-learn)
        """
        self.weights = weights or MatchingWeights()
        self.use_ml = use_ml and ML_AVAILABLE

        if self.use_ml:
            self.vectorizer = TfidfVectorizer(
                stop_words='english',
                ngram_range=(1, 2),
                max_features=5000,
                min_df=1
            )

        # Experience level mapping
        self.experience_mapping = {
            'entry level': 0,
            'junior': 1,
            'mid level': 2,
            'mid-level': 2,
            'senior': 3,
            'lead': 4,
            'principal': 5,
            'executive': 6,
            'director': 7,
            'vp': 8,
            'vice president': 8,
            'manager': 9
        }

        # Education level mapping
        self.education_mapping = {
            'high school': 0,
            'associate': 1,
            'diploma': 1,
            'bachelor': 2,
            'bs': 2,
            'ba': 2,
            "bachelor's": 2,
            'undergraduate': 2,
            'master': 3,
            'ms': 3,
            'ma': 3,
            'mba': 3,
            "master's": 3,
            'graduate': 3,
            'phd': 4,
            'doctorate': 4,
            'doctoral': 4
        }

    def normalize_skills(self, skills: List[str]) -> List[str]:
        """Normalize skill names for better matching"""
        if not skills:
            return []

        normalized = []
        skill_mapping = {
            'python': ['python', 'python3', 'python 3', 'py'],
            'javascript': ['javascript', 'js', 'ecmascript'],
            'typescript': ['typescript', 'ts'],
            'java': ['java', 'j2ee', 'j2se'],
            'c++': ['c++', 'cpp', 'c plus plus'],
            'c#': ['c#', 'csharp', 'c sharp'],
            'sql': ['sql', 'mysql', 'postgresql', 'oracle', 'database'],
            'aws': ['aws', 'amazon web services'],
            'azure': ['azure', 'microsoft azure'],
            'gcp': ['gcp', 'google cloud', 'google cloud platform'],
            'docker': ['docker', 'docker container'],
            'kubernetes': ['kubernetes', 'k8s'],
            'react': ['react', 'react.js', 'reactjs'],
            'angular': ['angular', 'angular.js', 'angularjs'],
            'vue': ['vue', 'vue.js', 'vuejs'],
            'node.js': ['node.js', 'node', 'nodejs'],
            'machine learning': ['machine learning', 'ml', 'ai'],
            'deep learning': ['deep learning', 'dl', 'neural networks'],
            'data science': ['data science', 'data analysis', 'data analytics']
        }

        for skill in skills:
            if not skill or not isinstance(skill, str):
                continue

            skill_lower = skill.lower().strip()
            found = False

            # Check if skill matches any mapped variations
            for base_skill, variations in skill_mapping.items():
                if skill_lower in variations or any(variation in skill_lower for variation in variations):
                    normalized.append(base_skill.title())
                    found = True
                    break

            if not found and skill_lower:
                normalized.append(skill.title())

        return list(set(normalized))  # Remove duplicates

    def calculate_skill_match(self, resume_skills: List[str], job_required_skills: List[str],
                            job_preferred_skills: List[str]) -> Tuple[float, List[str], List[str]]:
        """
        Calculate skill match score between resume and job

        Returns:
            Tuple of (match_score, matching_skills, missing_skills)
        """
        if not job_required_skills and not job_preferred_skills:
            return 1.0, [], []  # No skills required = perfect match

        resume_skills_norm = set(self.normalize_skills(resume_skills))
        job_required_norm = set(self.normalize_skills(job_required_skills))
        job_preferred_norm = set(self.normalize_skills(job_preferred_skills))

        # Calculate matches
        required_matches = resume_skills_norm.intersection(job_required_norm)
        preferred_matches = resume_skills_norm.intersection(job_preferred_norm)

        # Calculate scores with weights
        required_score = 0
        if job_required_norm:
            required_score = len(required_matches) / len(job_required_norm)
        else:
            required_score = 1.0  # No required skills = perfect score for this part

        preferred_score = 0
        if job_preferred_norm:
            preferred_score = len(preferred_matches) / len(job_preferred_norm) * 0.3  # Lower weight for preferred

        # Overall skill score (70% required, 30% preferred)
        skill_score = (required_score * 0.7) + (preferred_score * 0.3)

        # Find missing required skills
        missing_required = list(job_required_norm - resume_skills_norm)

        # All matching skills (both required and preferred)
        all_matching = list(required_matches.union(preferred_matches))

        return skill_score, all_matching, missing_required

    def extract_years_from_experience(self, experience_text: List[str]) -> Optional[int]:
        """Extract total years of experience from resume text"""
        if not experience_text:
            return None

        total_years = 0
        years_pattern = r'(\d+)\s*(?:year|yr)s?\s*(?:of)?\s*experience'

        for text in experience_text:
            if not text:
                continue
            matches = re.findall(years_pattern, text.lower())
            for match in matches:
                try:
                    total_years = max(total_years, int(match))
                except ValueError:
                    pass

        # If no explicit years found, estimate from job titles
        if total_years == 0:
            seniority_keywords = {
                'senior': 5,
                'lead': 6,
                'principal': 7,
                'manager': 4,
                'director': 8,
                'vp': 10,
                'vice president': 10,
                'junior': 1,
                'entry': 0,
                'mid': 3,
                'associate': 2
            }

            for text in experience_text:
                if not text:
                    continue
                text_lower = text.lower()
                for keyword, years in seniority_keywords.items():
                    if keyword in text_lower:
                        total_years = max(total_years, years)

        return total_years if total_years > 0 else None

    def estimate_experience_level(self, experience_text: List[str]) -> int:
        """Estimate experience level from resume text"""
        if not experience_text:
            return 2  # Default to mid-level

        max_score = 0

        for text in experience_text:
            if not text:
                continue
            text_lower = text.lower()
            for level, score in self.experience_mapping.items():
                if level in text_lower:
                    max_score = max(max_score, score)

        return max_score if max_score > 0 else 2  # Default to mid-level

    def calculate_experience_match(self, resume_experience_text: List[str],
                                 job_experience_level: Optional[str],
                                 job_years_experience: Optional[int] = None) -> float:
        """Calculate experience level match"""
        if not job_experience_level:
            return 1.0  # No experience requirement specified

        # Extract years from resume experience text
        resume_years = self.extract_years_from_experience(resume_experience_text)

        # Map job experience level to numeric value
        job_level_lower = job_experience_level.lower() if job_experience_level else ''
        job_level_score = self.experience_mapping.get(job_level_lower, 2)  # Default to mid-level

        # If years specified in job, calculate years match
        years_score = None
        if job_years_experience is not None and resume_years is not None:
            if resume_years >= job_years_experience:
                years_score = 1.0
            else:
                years_score = resume_years / max(job_years_experience, 1)

        # If years not specified, use level mapping
        resume_level_score = self.estimate_experience_level(resume_experience_text)

        # Calculate similarity between levels
        if resume_level_score >= job_level_score:
            level_score = 1.0
        else:
            level_score = resume_level_score / max(job_level_score, 1)

        # Combine years and level scores
        if years_score is not None:
            return (level_score * 0.4) + (years_score * 0.6)
        else:
            return level_score

    def extract_highest_education_level(self, education_text: List[str]) -> int:
        """Extract highest education level from resume"""
        if not education_text:
            return 2  # Default to Bachelor's

        highest_level = 0

        for text in education_text:
            if not text:
                continue
            text_lower = text.lower()
            for degree, level in self.education_mapping.items():
                if degree in text_lower:
                    highest_level = max(highest_level, level)

        return highest_level if highest_level > 0 else 2  # Default to Bachelor's

    def extract_required_education_level(self, education_requirements: List[str]) -> int:
        """Extract required education level from job description"""
        if not education_requirements:
            return 2  # Default to Bachelor's

        highest_required = 0

        for req in education_requirements:
            if not req:
                continue
            req_lower = req.lower()
            for degree, level in self.education_mapping.items():
                if degree in req_lower and ('required' in req_lower or 'must' in req_lower or 'minimum' in req_lower):
                    highest_required = max(highest_required, level)

        return highest_required if highest_required > 0 else 2  # Default to Bachelor's

    def calculate_education_match(self, resume_education: List[str],
                                job_education_requirements: List[str]) -> float:
        """Calculate education match score"""
        if not job_education_requirements:
            return 1.0  # No education requirement

        # Extract highest degree from resume
        resume_highest_level = self.extract_highest_education_level(resume_education)

        # Extract required degree from job
        job_required_level = self.extract_required_education_level(job_education_requirements)

        if resume_highest_level >= job_required_level:
            return 1.0
        else:
            return resume_highest_level / max(job_required_level, 1)

    def calculate_keyword_similarity(self, resume_text: str, job_text: str) -> float:
        """Calculate keyword similarity using TF-IDF and cosine similarity"""
        if not resume_text or not job_text:
            return 0.0

        # Clean texts
        resume_text_clean = str(resume_text).strip()
        job_text_clean = str(job_text).strip()

        if not resume_text_clean or not job_text_clean:
            return 0.0

        # Use ML-based similarity if available
        if self.use_ml:
            try:
                # Combine texts and fit TF-IDF
                texts = [resume_text_clean, job_text_clean]
                tfidf_matrix = self.vectorizer.fit_transform(texts)

                # Calculate cosine similarity
                similarity_matrix = cosine_similarity(tfidf_matrix[0:1], tfidf_matrix[1:2])

                return float(similarity_matrix[0][0])
            except Exception as e:
                print(f"ML similarity failed, using fallback: {e}")

        # Fallback to simple word overlap
        resume_words = set(re.findall(r'\b\w+\b', resume_text_clean.lower()))
        job_words = set(re.findall(r'\b\w+\b', job_text_clean.lower()))

        if not job_words:
            return 0.0

        overlap = len(resume_words.intersection(job_words))
        return overlap / len(job_words)

    def check_location_match(self, resume_locations: List[str], job_location: str) -> bool:
        """Check if resume locations match job location"""
        if not job_location or not job_location.strip():
            return True

        job_loc_lower = job_location.lower().strip()

        # Check for remote/hybrid indicators
        remote_indicators = ['remote', 'work from home', 'wfh', 'anywhere', 'flexible', 'distributed']
        if any(indicator in job_loc_lower for indicator in remote_indicators):
            return True

        if not resume_locations:
            return False

        # Check if any resume location matches job location
        for resume_loc in resume_locations:
            if not resume_loc:
                continue
            if resume_loc.lower() in job_loc_lower or job_loc_lower in resume_loc.lower():
                return True

        return False

    def check_remote_match(self, resume_text: str, job_remote_option: bool) -> bool:
        """Check if resume indicates remote work compatibility"""
        if not job_remote_option:
            return True  # If job is not remote, any resume is compatible

        if not resume_text:
            return False

        # Check if resume mentions remote work experience or preference
        remote_keywords = ['remote', 'work from home', 'wfh', 'distributed team',
                          'telecommute', 'virtual', 'remote work', 'hybrid']

        resume_lower = resume_text.lower()
        return any(keyword in resume_lower for keyword in remote_keywords)

    def generate_recommendations(self, missing_skills: List[str],
                               match_scores: Dict[str, float]) -> List[str]:
        """Generate recommendations for improving match"""
        recommendations = []

        # Skill-based recommendations
        if missing_skills:
            if len(missing_skills) <= 3:
                recommendations.append(f"Learn these key skills: {', '.join(missing_skills[:3])}")
            else:
                recommendations.append(f"Focus on learning these top skills: {', '.join(missing_skills[:3])}")

        # Score-based recommendations
        if match_scores.get('skill_score', 0) < 0.5:
            recommendations.append("Consider gaining more experience with required technical skills")

        if match_scores.get('experience_score', 0) < 0.5:
            recommendations.append("Highlight more relevant experience in your resume")

        if match_scores.get('education_score', 0) < 0.5:
            recommendations.append("Consider additional certifications or education relevant to the role")

        # General recommendations
        if len(recommendations) < 3:
            recommendations.append("Tailor your resume to include more keywords from the job description")
            recommendations.append("Highlight achievements and quantifiable results in your experience")
            recommendations.append("Obtain relevant certifications to strengthen your profile")

        return recommendations[:5]  # Return top 5 recommendations

    def match_resume_to_job(self, resume: ResumeEntity, job: JobEntity) -> MatchResult:
        """
        Match a single resume to a single job description

        Args:
            resume: ResumeEntity object from Resume Parser
            job: JobEntity object from Job Description Parser

        Returns:
            MatchResult object with detailed matching information
        """
        # Ensure we have valid data
        if not resume or not job:
            raise ValueError("Resume and Job entities must not be None")

        # Calculate individual match scores
        skill_score, matching_skills, missing_skills = self.calculate_skill_match(
            resume.skills if hasattr(resume, 'skills') else [],
            job.required_skills if hasattr(job, 'required_skills') else [],
            job.preferred_skills if hasattr(job, 'preferred_skills') else []
        )

        experience_score = self.calculate_experience_match(
            resume.experience if hasattr(resume, 'experience') else [],
            job.experience_level if hasattr(job, 'experience_level') else None
        )

        education_score = self.calculate_education_match(
            resume.education if hasattr(resume, 'education') else [],
            job.education_requirements if hasattr(job, 'education_requirements') else []
        )

        keyword_score = self.calculate_keyword_similarity(
            resume.raw_text if hasattr(resume, 'raw_text') else "",
            job.raw_text if hasattr(job, 'raw_text') else ""
        )

        location_match = self.check_location_match(
            resume.locations if hasattr(resume, 'locations') else [],
            job.location if hasattr(job, 'location') else ""
        )

        remote_match = self.check_remote_match(
            resume.raw_text if hasattr(resume, 'raw_text') else "",
            job.remote_option if hasattr(job, 'remote_option') else False
        )

        # Calculate location and remote scores
        location_score = 1.0 if location_match else 0.0
        remote_score = 1.0 if remote_match else 0.5  # Partial score if remote not mentioned

        # Create match breakdown
        match_breakdown = {
            'skill_score': skill_score,
            'experience_score': experience_score,
            'education_score': education_score,
            'keyword_score': keyword_score,
            'location_score': location_score,
            'remote_score': remote_score
        }

        # Calculate weighted overall score
        overall_score = (
            skill_score * self.weights.skill_weight +
            experience_score * self.weights.experience_weight +
            education_score * self.weights.education_weight +
            keyword_score * self.weights.keyword_weight +
            location_score * self.weights.location_weight +
            remote_score * self.weights.remote_weight
        ) / self.weights.total()

        # Ensure score is between 0 and 1
        overall_score = max(0.0, min(1.0, overall_score))

        # Generate recommendations
        recommendations = self.generate_recommendations(missing_skills, match_breakdown)

        # Get resume and job identifiers
        resume_id = resume.name if hasattr(resume, 'name') and resume.name else 'Unknown'
        job_id = job.job_title if hasattr(job, 'job_title') and job.job_title else 'Unknown'

        # Create result
        result = MatchResult(
            resume_id=resume_id,
            job_id=job_id,
            overall_score=overall_score,
            skill_match_score=skill_score,
            experience_match_score=experience_score,
            education_match_score=education_score,
            keyword_match_score=keyword_score,
            match_breakdown=match_breakdown,
            matching_skills=matching_skills,
            missing_skills=missing_skills,
            recommendations=recommendations,
            is_remote_match=remote_match,
            location_match=location_match
        )

        return result

    def match_multiple(self, resumes: List[ResumeEntity], jobs: List[JobEntity],
                      top_n: int = 5) -> Dict[str, List[MatchResult]]:
        """
        Match multiple resumes to multiple jobs

        Args:
            resumes: List of ResumeEntity objects from Resume Parser
            jobs: List of JobEntity objects from Job Description Parser
            top_n: Number of top matches to return per resume

        Returns:
            Dictionary with resume names as keys and lists of top matches as values
        """
        if not resumes or not jobs:
            return {}

        all_matches = {}

        for resume in resumes:
            if not resume:
                continue

            resume_matches = []

            for job in jobs:
                if not job:
                    continue

                try:
                    match_result = self.match_resume_to_job(resume, job)
                    resume_matches.append(match_result)
                except Exception as e:
                    print(f"Error matching resume to job: {e}")
                    continue

            # Sort by overall score descending
            resume_matches.sort(key=lambda x: x.overall_score, reverse=True)

            # Store top N matches
            resume_name = resume.name if hasattr(resume, 'name') and resume.name else f"Resume_{len(all_matches)}"
            all_matches[resume_name] = resume_matches[:top_n]

        return all_matches

    def create_comparison_matrix(self, resumes: List[ResumeEntity],
                               jobs: List[JobEntity]) -> pd.DataFrame:
        """Create a matrix showing match scores between all resumes and jobs"""
        if not resumes or not jobs:
            return pd.DataFrame()

        data = []

        for i, resume in enumerate(resumes):
            if not resume:
                continue

            resume_name = resume.name if hasattr(resume, 'name') and resume.name else f'Resume_{i}'
            row = {'Resume': resume_name}

            for j, job in enumerate(jobs):
                if not job:
                    continue

                try:
                    match_result = self.match_resume_to_job(resume, job)
                    job_name = job.job_title if hasattr(job, 'job_title') and job.job_title else f'Job_{j}'
                    row[job_name] = round(match_result.overall_score * 100, 1)  # As percentage
                except Exception as e:
                    job_name = job.job_title if hasattr(job, 'job_title') and job.job_title else f'Job_{j}'
                    row[job_name] = 0.0

            data.append(row)

        return pd.DataFrame(data)

