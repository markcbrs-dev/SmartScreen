class IntegratedMatcher:
    """Class that integrates Resume Parser, Job Parser, and Matcher"""

    def __init__(self, use_ml: bool = True):
        """
        Initialize the integrated matcher

        Args:
            use_ml: Whether to use ML-based matching
        """
        self.use_ml = use_ml
        self.matcher = ResumeJobMatcher(use_ml=use_ml)

    def load_resume_parser(self):
        """Load the Resume Parser module"""
        try:
            # Try to import from resume_parser.py (your file)
            try:
                # Since your file is named resume_parser.py
                from resume_parser import ResumeParser
                self.resume_parser = ResumeParser()
                print("✓ Loaded resume_parser.py successfully")
                return True
            except ImportError as e:
                print(f"❌ Failed to import from resume_parser.py: {e}")

                # Check if the file exists
                import os
                if os.path.exists("resume_parser.py"):
                    print("   File exists but import failed. Checking the module...")
                    # Try alternative import
                    try:
                        import importlib.util
                        spec = importlib.util.spec_from_file_location("resume_parser", "resume_parser.py")
                        module = importlib.util.module_from_spec(spec)
                        spec.loader.exec_module(module)
                        self.resume_parser = module.ResumeParser()
                        print("✓ Loaded resume_parser using importlib")
                        return True
                    except Exception as e2:
                        print(f"   Importlib also failed: {e2}")
                else:
                    print("❌ resume_parser.py not found in current directory")

                return False
        except Exception as e:
            print(f"❌ Error loading Resume Parser: {e}")
            import traceback
            traceback.print_exc()
            return False

    def load_job_parser(self):
        """Load the Job Description Parser module"""
        try:
            from job_description_parser import JobDescriptionParser
            self.job_parser = JobDescriptionParser()
            print("✓ Loaded job_description_parser")
            return True
        except ImportError as e:
            print(f"❌ Failed to import Job Description Parser: {e}")
            print("Please ensure job_description_parser.py is in the same directory")
            return False

    def parse_resumes(self, resumes_folder: str) -> List[ResumeEntity]:
        """Parse resumes from folder"""
        if not hasattr(self, 'resume_parser'):
            if not self.load_resume_parser():  # Fixed method name
                return []

        print(f"📄 Parsing resumes from: {resumes_folder}")
        resumes = self.resume_parser.parse_multiple_resumes(resumes_folder)
        print(f"   Found {len(resumes)} resumes")
        return resumes

    def parse_resume_file(self, resume_file: str) -> ResumeEntity:
        """Parse a single resume file"""
        if not hasattr(self, 'resume_parser'):
            if not self.load_resume_parser():  # Fixed method name
                return None

        print(f"📄 Parsing resume: {resume_file}")
        resume = self.resume_parser.parse_resume(resume_file)
        return resume

    def parse_job_file(self, job_file: str) -> JobEntity:
        """Parse a single job description file"""
        if not hasattr(self, 'job_parser'):
            if not self.load_job_parser():
                return None

        print(f"📋 Parsing job description: {job_file}")
        job = self.job_parser.parse_job_description(job_file)
        return job

    def match_resume_job_files(self, resume_file: str, job_file: str) -> MatchResult:
        """Match a single resume file with a single job file"""
        resume = self.parse_resume_file(resume_file)
        if not resume:
            return None

        job = self.parse_job_file(job_file)
        if not job:
            return None

        print("🤝 Matching resume with job...")
        result = self.matcher.match_resume_to_job(resume, job)
        return result

    def match_folders(self, resumes_folder: str, jobs_folder: str,
                     top_n: int = 5) -> Dict[str, List[MatchResult]]:
        """Match all resumes in folder with all jobs in folder"""
        resumes = self.parse_resumes(resumes_folder)
        if not resumes:
            return {}

        jobs = self.parse_jobs(jobs_folder)
        if not jobs:
            return {}

        print("🤝 Matching resumes with jobs...")
        all_matches = self.matcher.match_multiple(resumes, jobs, top_n=top_n)
        return all_matches

    def match_parsed_data(self, resumes: List[ResumeEntity], jobs: List[JobEntity],
                         top_n: int = 5) -> Dict[str, List[MatchResult]]:
        """Match already parsed resume and job data"""
        if not resumes or not jobs:
            return {}

        print("🤝 Matching parsed resumes with jobs...")
        all_matches = self.matcher.match_multiple(resumes, jobs, top_n=top_n)
        return all_matches

    def save_results(self, matches_dict: Dict[str, List[MatchResult]],
                    output_format: str = 'csv', prefix: str = 'match_results'):
        """Save matching results to file"""
        import datetime
        timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")

        # Save detailed matches
        detailed_data = []
        for resume_name, matches in matches_dict.items():
            for match in matches:
                detailed_data.append({
                    'Resume': resume_name,
                    'Job_Title': match.job_id,
                    'Overall_Score_%': round(match.overall_score * 100, 1),
                    'Skill_Score_%': round(match.skill_match_score * 100, 1),
                    'Experience_Score_%': round(match.experience_match_score * 100, 1),
                    'Education_Score_%': round(match.education_match_score * 100, 1),
                    'Matching_Skills_Count': len(match.matching_skills),
                    'Missing_Skills_Count': len(match.missing_skills),
                    'Location_Match': match.location_match,
                    'Remote_Match': match.is_remote_match,
                    'Top_Matching_Skills': ', '.join(match.matching_skills[:5]) if match.matching_skills else '',
                    'Top_Missing_Skills': ', '.join(match.missing_skills[:3]) if match.missing_skills else ''
                })

        detailed_df = pd.DataFrame(detailed_data)

        # Save based on format
        if output_format == 'csv':
            filename = f'{prefix}_{timestamp}.csv'
            detailed_df.to_csv(filename, index=False)
            print(f"💾 Results saved to: {filename}")
            return filename

        elif output_format == 'json':
            filename = f'{prefix}_{timestamp}.json'
            results_dict = {
                'timestamp': timestamp,
                'detailed_matches': detailed_data
            }

            with open(filename, 'w', encoding='utf-8') as f:
                json.dump(results_dict, f, indent=2, ensure_ascii=False)
            print(f"💾 Results saved to: {filename}")
            return filename

        elif output_format == 'excel':
            try:
                import openpyxl
                filename = f'{prefix}_{timestamp}.xlsx'
                with pd.ExcelWriter(filename, engine='openpyxl') as writer:
                    detailed_df.to_excel(writer, sheet_name='Matches', index=False)
                print(f"💾 Results saved to: {filename}")
                return filename
            except ImportError:
                print("❌ openpyxl not installed for Excel export. Install with: pip install openpyxl")
                filename = f'{prefix}_{timestamp}.csv'
                detailed_df.to_csv(filename, index=False)
                print(f"💾 Results saved to CSV instead: {filename}")
                return filename

        return None


